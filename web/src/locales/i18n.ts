export const I18nService = {
  getLanguage(): AppLanguage {
    if (typeof window === 'undefined') return 'vi';
    return (localStorage.getItem(LANGUAGE_KEY) as AppLanguage) || 'vi';
  },

  setLanguage(lang: AppLanguage): void {
    if (typeof window === 'undefined') return;
    localStorage.setItem(LANGUAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent('ontapgplx:language_change', { detail: lang }));
  },

  t(key: string, lang?: AppLanguage): string {
    const currentLang = lang || this.getLanguage();
    const dictionary = TRANSLATIONS[currentLang] || TRANSLATIONS.vi;
    return dictionary[key] || TRANSLATIONS.vi[key] || key;
  }
};

