export const I18nService = {
  getLanguage(): AppLanguage {
    if (typeof window !== 'undefined' && localStorage.getItem(LANGUAGE_KEY)) {
      localStorage.removeItem(LANGUAGE_KEY);
    }
    return 'vi';
  },

  setLanguage(_lang: AppLanguage): void {
    if (typeof window === 'undefined') return;
    localStorage.removeItem(LANGUAGE_KEY);
    window.dispatchEvent(new CustomEvent('ontapgplx:language_change', { detail: 'vi' }));
  },

  t(key: string, _lang?: AppLanguage): string {
    const dictionary = TRANSLATIONS.vi;
    return dictionary[key] || key;
  }
};

